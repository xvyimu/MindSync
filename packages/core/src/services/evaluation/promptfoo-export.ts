/**
 * Minimal Promptfoo config exporter (Cut-R2a / C2).
 *
 * Pure adapter: maps EvalCaseSet + prompt text → promptfoo.yaml.
 * Does NOT vendor Promptfoo, run evals, or embed API keys.
 */

import type { EvalAssertion, EvalCase, EvalCaseSet } from './eval-case-types';

export interface PromptfooExportInput {
  /** Primary prompt text to evaluate (usually optimized; fall back to original). */
  prompt: string;
  /** Optional second prompt (e.g. original) exported as an additional prompts entry. */
  secondaryPrompt?: string;
  /** Case set providing tests/assertions. */
  caseSet: EvalCaseSet;
  /** Free-form description line. */
  description?: string;
}

export interface PromptfooExportResult {
  yaml: string;
  fileName: string;
  /** Assertion types that could not be mapped (should be empty for Cut-1 types). */
  skippedAssertionTypes: string[];
}

const YAML_UNSAFE = /[:#{}[\],&*!|>'"%@`]/;

function escapeYamlDoubleQuoted(value: string): string {
  return value.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\n/g, '\\n');
}

function yamlScalar(value: string): string {
  if (value === '') return '""';
  if (/^\s|\s$/.test(value) || YAML_UNSAFE.test(value) || value.includes('\n')) {
    return `"${escapeYamlDoubleQuoted(value)}"`;
  }
  return value;
}

function mapAssertion(assertion: EvalAssertion): { line: string } | { skip: string } {
  if (assertion.type === 'contains') {
    return {
      line: `      - type: contains\n        value: ${yamlScalar(assertion.value)}`,
    };
  }
  if (assertion.type === 'not_contains') {
    // Promptfoo uses not-contains
    return {
      line: `      - type: not-contains\n        value: ${yamlScalar(assertion.value)}`,
    };
  }
  return { skip: (assertion as { type: string }).type };
}

function mapCase(evalCase: EvalCase): { block: string; skipped: string[] } {
  const skipped: string[] = [];
  const assertLines: string[] = [];
  for (const assertion of evalCase.assertions) {
    const mapped = mapAssertion(assertion);
    if ('skip' in mapped) {
      skipped.push(mapped.skip);
      continue;
    }
    assertLines.push(mapped.line);
  }

  if (assertLines.length === 0) {
    return { block: '', skipped };
  }

  const description = evalCase.name?.trim() ? yamlScalar(evalCase.name.trim()) : undefined;
  const varsInput = yamlScalar(evalCase.input);
  const lines = [
    '  - description: ' + (description ?? yamlScalar(evalCase.id)),
    '    vars:',
    `      input: ${varsInput}`,
    '    assert:',
    ...assertLines,
  ];
  return { block: lines.join('\n'), skipped };
}

/**
 * Build a minimal promptfoo.yaml string from a case set + prompt text.
 * Never includes API keys or provider credentials.
 */
export function exportPromptfooYaml(input: PromptfooExportInput): PromptfooExportResult {
  const prompt = (input.prompt ?? '').trim();
  if (!prompt) {
    throw new Error('prompt is required for promptfoo export');
  }
  if (!input.caseSet || !Array.isArray(input.caseSet.cases)) {
    throw new Error('caseSet with cases is required for promptfoo export');
  }

  const skippedAssertionTypes: string[] = [];
  const testBlocks: string[] = [];

  for (const evalCase of input.caseSet.cases) {
    const { block, skipped } = mapCase(evalCase);
    skippedAssertionTypes.push(...skipped);
    if (block) testBlocks.push(block);
  }

  if (testBlocks.length === 0) {
    throw new Error('No exportable tests (need at least one case with contains/not_contains)');
  }

  const prompts: string[] = [prompt];
  const secondary = input.secondaryPrompt?.trim();
  if (secondary && secondary !== prompt) {
    prompts.push(secondary);
  }

  const description =
    input.description?.trim() ||
    `prompt-optimizer export · ${input.caseSet.name || input.caseSet.id}`;

  const header = [
    '# Generated by prompt-optimizer (minimal contains mapping).',
    '# No API keys included. Run with your own providers via promptfoo CLI.',
    `# caseSetId: ${input.caseSet.id}`,
    `description: ${yamlScalar(description)}`,
    'prompts:',
    ...prompts.map((p) => `  - ${yamlScalar(p)}`),
    'tests:',
    ...testBlocks,
    '',
  ];

  return {
    yaml: header.join('\n'),
    fileName: createPromptfooExportFileName(),
    skippedAssertionTypes: [...new Set(skippedAssertionTypes)],
  };
}

export function createPromptfooExportFileName(date: Date = new Date()): string {
  const pad = (n: number) => String(n).padStart(2, '0');
  const stamp = [
    date.getFullYear(),
    pad(date.getMonth() + 1),
    pad(date.getDate()),
    '-',
    pad(date.getHours()),
    pad(date.getMinutes()),
    pad(date.getSeconds()),
  ].join('');
  return `promptfoo-export-${stamp}.yaml`;
}

/** Guard: exported yaml must not look like it embeds secrets. */
export function assertPromptfooYamlHasNoSecrets(yaml: string): void {
  const patterns = [
    /\bapiKey\b/i,
    /\bapi_key\b/i,
    /\bAuthorization\b/i,
    /\bsk-[A-Za-z0-9]{10,}/,
    /\bbearer\s+[A-Za-z0-9._\-]{10,}/i,
  ];
  for (const re of patterns) {
    if (re.test(yaml)) {
      throw new Error(`promptfoo export must not contain secrets (matched ${re})`);
    }
  }
}
